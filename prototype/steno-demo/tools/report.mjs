// Collects the evaluation and robustness results into one module the demo can show.
//
//   node tools/report.mjs
//
// Runs tools/evaluate.mjs and tools/robustness.mjs and writes src/eval.generated.js.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const run = script => JSON.parse(execFileSync(process.execPath, [path.join(here, script), '--json'], { maxBuffer: 1 << 26 }).toString());
const evaluation = run('evaluate.mjs').results;
const robustness = run('robustness.mjs');
const r1 = x => +x.toFixed(1), r2 = x => +x.toFixed(2), r3 = x => +x.toFixed(3);

const slim = {};
for (const [corpus, r] of Object.entries(evaluation)) {
  slim[corpus] = {
    messages: r.messages, chars: r.chars, letterStrokesPerWord: r2(r.letterStrokesPerWord),
    letterWpm: Object.fromEntries(Object.entries(r.letterWpm).map(([k, v]) => [k, r1(v)])),
    stages: r.rows.map(row => ({
      stage: row.stage, strokesPerWord: r2(row.strokesPerWord), chordsPerWord: r2(row.chordsPerWord), saving: r1(row.saving * 100), chordSaving: r1(row.chordSaving * 100),
      wpm: Object.fromEntries(Object.entries(row.wpm).map(([k, v]) => [k, r1(v)])),
      share: Object.fromEntries(Object.entries(row.share).map(([k, v]) => [k, r1(v * 100)])),
    })),
  };
}
const grid = robustness.grid.map(g => ({
  leg: g.leg, aim: g.aim,
  kinds: Object.fromEntries(Object.entries(g.kinds).map(([k, o]) => [k, Object.fromEntries(Object.entries(o).map(([n, v]) => [n, r3(v)]))])),
}));

fs.writeFileSync(path.join(here, '..', 'src', 'eval.generated.js'),
  `// Generated by tools/report.mjs. Do not edit.\nexport default ${JSON.stringify({ evaluation: slim, robustness: { key: robustness.key, grid } }, null, 1)};\n`);
console.log('wrote src/eval.generated.js');
